/**
 * Platform migrations: run after the bot's (src/db/schema.js) and the CRM's
 * (crm/src/migrations.js), tracked in platform_migrations.
 *
 * From K8 on, ALL new migrations go here, so there is one order on fresh and on
 * existing databases. The bot and CRM lists are frozen (test/tenancy.test.js checks).
 * Never edit an applied migration; add a new one.
 *
 * Every new table that holds client data needs: tenant_id INTEGER NOT NULL
 * DEFAULT ${TENANT_DEFAULT} REFERENCES tenants (id), and the isolation policy
 * (tenancyPolicy below). test/tenancy.test.js fails for a table without them.
 */

// The current tenant, set per connection by src/db/index.js. Empty outside a tenant.
const TENANT_DEFAULT = "NULLIF(current_setting('app.tenant_id', true), '')::integer";
// A row is visible when it belongs to the current tenant, or when system work (all tenants) runs.
const VISIBLE = `current_setting('app.all_tenants', true) = 'on' OR tenant_id = ${TENANT_DEFAULT}`;

/** Row-level security for one table. FORCE makes it apply to the table owner too (Heroku's app role). */
const tenancyPolicy = table => [
  `ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY`,
  `ALTER TABLE ${table} FORCE ROW LEVEL SECURITY`,
  `CREATE POLICY tenant_isolation ON ${table} USING (${VISIBLE}) WITH CHECK (${VISIBLE})`
];

